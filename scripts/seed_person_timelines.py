def main() -> None:
    events_path = DATA / "events.json"
    persons_path = DATA / "persons.json"
    events = json.loads(events_path.read_text(encoding="utf-8"))
    persons = {person["id"]: person for person in json.loads(persons_path.read_text(encoding="utf-8"))}
    existing_ids = {event["id"] for event in events}
    for person in PEOPLE:
        persons[person["id"]] = {key: person[key] for key in ("id", "name", "description", "color")}
        for index, entry in enumerate(person["nodes"], start=1):
            event_id = f"p_{person['id']}_{index:02d}"
            if event_id in existing_ids:
                continue
            stage = entry["stage"]
            events.append({
                "id": event_id,
                "title": entry["title"],
                "year": entry["year"],
                "period": "人物生平时间线",
                "province": entry["province"],
                "city": entry["city"],
                "district": entry["district"],
                "kind": "event",
                "themes": [],
                "people": [person["name"]],
                "coords": entry["coords"],
                "summary": entry["note"],
                "story": entry["note"] + f" 该节点位于{entry['year']}年前后，是{person['name']}人生道路和中国革命、建设或改革历程的重要交汇点。",
                "tags": ["人物线", entry["stage_label"]],
                "timeline_type": stage,
            })
            existing_ids.add(event_id)
    events_path.write_text(json.dumps(events, ensure_ascii=False, indent=2), encoding="utf-8")
    persons_path.write_text(json.dumps(list(persons.values()), ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"persons={len(persons)} events={len(events)}")


if __name__ == "__main__":
    main()
